interface ShowInput {
  eventSlug: string;
  showAt: string;
  totalSeats: number;
  heldSeats?: number;
  isClosed?: boolean;
  note?: string;
}

let showSeq = 0;

function makeShow(input: ShowInput): Show {
  const event = events.find((e) => e.slug === input.eventSlug);
  if (!event) {
    throw new Error(`makeShow: unknown event slug "${input.eventSlug}"`);
  }
  showSeq += 1;
  const heldSeats = input.heldSeats ?? 0;
  return {
    id: `show_${String(showSeq).padStart(3, "0")}`,
    eventId: event.id,
    showAt: input.showAt,
    totalSeats: input.totalSeats,
    heldSeats,
    isClosed: input.isClosed ?? heldSeats >= input.totalSeats,
    note: input.note ?? null,
  };
}

