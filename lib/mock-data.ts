let eventSeq = 0;

function makeEvent(input: EventInput): Event {
  eventSeq += 1;
  return {
    id: `evt_${String(eventSeq).padStart(3, "0")}`,
    slug: input.slug,
    title: input.title,
    category: input.category,
    status: "PUBLISHED",
    summary: input.summary,
    description: input.description ?? input.summary,
    startDate: input.startDate,
    endDate: input.endDate,
    timeNote: input.timeNote ?? null,
    isAlwaysOpen: input.isAlwaysOpen ?? false,
    zoneId: input.zoneId,
    venueName: input.venueName,
    address: input.address,
    lat: input.lat,
    lng: input.lng,
    isFree: input.isFree ?? false,
    priceNote: input.priceNote ?? null,
    hasInvite: input.hasInvite ?? false,
    thumbnailUrl: `https://picsum.photos/seed/nolzido-${input.thumbnailSeed}/800/600`,
    images: [],
    source: "MANUAL",
    sourceUrl: null,
    externalId: null,
    isSponsored: false,
    priority: 0,
    viewCount: 0,
    likeCount: 0,
    partnerId: null,
    tags: input.tags ?? [],
    createdAt: "2026-07-01T00:00:00+09:00",
    updatedAt: "2026-07-01T00:00:00+09:00",
  };
}

